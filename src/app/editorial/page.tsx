/**
 * Editorial index.
 *
 * Published articles only. Drafts are visible from the content studio, never
 * here — the filter is applied in SQL rather than in the component, so a draft
 * cannot reach a public surface even if a component forgets to check.
 */
import { ArticleCard, PageHeader } from '@/components/cards';
import { Badge, Callout, Card, CardBody, CardHeader, CardTitle, EmptyState } from '@/components/ui/primitives';
import { listArticles, listSources } from '@/lib/data/editorial';
import { formatDate, pluralize } from '@/lib/format';

export const dynamic = 'force-dynamic';

export default async function EditorialPage() {
  const [articles, sources] = await Promise.all([listArticles(), listSources()]);

  const [lead, ...rest] = articles;

  return (
    <div className="flex flex-col gap-7">
      <PageHeader
        eyebrow="Editorial"
        title="Market reports and analyses"
        description="Long-form pieces from the analyst and editorial desks. Every report is written against the same dataset the dashboards read, so the numbers in the prose and the numbers on the charts come from one place."
        action={<Badge tone="outline">{pluralize(articles.length, 'published report')}</Badge>}
      />

      {articles.length === 0 ? (
        <EmptyState
          title="No reports published yet"
          description="Publish one from the content studio and it will appear here immediately."
        />
      ) : (
        <>
          {lead ? (
            <div className="grid gap-4 lg:grid-cols-[1.6fr_1fr]">
              <ArticleCard article={lead} featured />
              <Card>
                <CardHeader>
                  <CardTitle as="h2">In this issue</CardTitle>
                </CardHeader>
                <CardBody className="flex flex-col gap-3">
                  {articles.slice(1, 6).map((article) => (
                    <div key={article.slug} className="border-b border-line pb-3 last:border-0 last:pb-0">
                      <p className="text-[13px] leading-snug text-ink">{article.title}</p>
                      <p className="mt-1 text-[11px] text-ink-subtle">
                        {article.readingMinutes} min · {formatDate(article.publishedAt)}
                      </p>
                    </div>
                  ))}
                </CardBody>
              </Card>
            </div>
          ) : null}

          <section>
            <h2 className="mb-4 text-lg font-semibold tracking-tight">All reports</h2>
            <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
              {rest.map((article) => (
                <ArticleCard key={article.slug} article={article} />
              ))}
            </div>
          </section>
        </>
      )}

      <Card>
        <CardHeader>
          <div>
            <CardTitle as="h2">Sources</CardTitle>
            <p className="mt-0.5 text-xs text-ink-subtle">
              Every analyst note is attributed to a registered source. Retail floor checks are the
              useful counterweight to platform data — they are not affected by bid/ask dynamics.
            </p>
          </div>
        </CardHeader>
        <CardBody className="flex flex-col divide-y divide-line">
          {sources.map((source) => (
            <div key={source.id} className="flex flex-wrap items-center justify-between gap-2 py-2.5">
              <div className="min-w-0">
                <p className="text-[13px] text-ink">{source.name}</p>
                {source.notes ? (
                  <p className="mt-0.5 text-[11px] text-ink-subtle">{source.notes}</p>
                ) : null}
              </div>
              <div className="flex items-center gap-2">
                <Badge tone="outline">{source.kind}</Badge>
                <span className="tnum text-[11px] text-ink-subtle">
                  {pluralize(source.insightCount, 'note')}
                </span>
              </div>
            </div>
          ))}
        </CardBody>
      </Card>

      <Callout tone="neutral" title="About the dataset">
        Product names reference real silhouettes. All prices, volumes and listing counts in the demo
        dataset are synthetic, generated by a seeded process so that every figure on this site is
        reproducible and the test suite is deterministic.
      </Callout>
    </div>
  );
}
